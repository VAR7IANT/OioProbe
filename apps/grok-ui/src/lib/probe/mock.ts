function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

function mixToEnd(raw: number, target: number, index: number, length: number): number {
  const t = index / Math.max(1, length - 1);
  const blend = Math.max(0, (t - 0.82) / 0.18);
  return raw * (1 - blend) + target * blend;
}

function buildRecent(spec: Spec, end: number): Record<RangeKey, KomariRecord[]> {
  const memTotal = gb(spec.memGb);
  const diskTotal = gb(spec.diskGb);
  const ranges = Object.keys(RANGES) as RangeKey[];
  return ranges.reduce(
    (accumulator, range) => {
      const { points, step } = RANGES[range];
      accumulator[range] = Array.from({ length: points }, (_, index) => {
        const t = index / Math.max(1, points - 1);
        const seasonal = Math.sin(t * Math.PI * 2 + spec.seed) ;
        const local = Math.sin(index * 0.57 + spec.seed * 1.6);
        const cpuRaw = spec.cpu * 0.86 + seasonal * Math.max(4, spec.cpu * 0.12) + local * 2.2;
        const memRaw = spec.mem * 0.9 + Math.sin(t * Math.PI * 2 + spec.seed * 0.6) * 3 + local * 1.1;
        const cpu = clamp(mixToEnd(cpuRaw, spec.cpu, index, points), 0.4, 99);
        const mem = clamp(mixToEnd(memRaw, spec.mem, index, points), 0.4, 99);
        const netFactor = mixToEnd(1 + seasonal * 0.22 + local * 0.08, 1, index, points);
        const time = new Date(end - (points - 1 - index) * step).toISOString();
        const record: KomariRecord = {
          client: spec.id,
          time,
          cpu: Math.round(cpu * 10) / 10,
          ram: Math.round((memTotal * mem) / 100),
          ram_total: memTotal,
          load: Math.round(spec.load1 * (cpu / Math.max(spec.cpu, 1)) * 100) / 100,
          load5: spec.load5,
          load15: spec.load15,
          disk: Math.round((diskTotal * spec.disk) / 100),
          disk_total: diskTotal,
          net_in: Math.max(0, Math.round(spec.down * netFactor)),
          net_out: Math.max(0, Math.round(spec.up * netFactor)),
          net_total_up: Math.round(spec.uptimeSec * spec.up * 0.58),
          net_total_down: Math.round(spec.uptimeSec * spec.down * 0.63),
          process: spec.process,
          connections: spec.connections,
          connections_udp: spec.udp,
          temp: spec.temp,
        };
        return record;
      });
      return accumulator;
    },
    {} as Record<RangeKey, KomariRecord[]>,
  );
}

function buildPing(spec: Spec, recent: Record<RangeKey, KomariRecord[]>): Record<RangeKey, KomariPingSample[]> {
  const ranges = Object.keys(RANGES) as RangeKey[];
  if (spec.ping == null || spec.loss == null) {
    return ranges.reduce(
      (accumulator, range) => {
        accumulator[range] = [];
        return accumulator;
      },
      {} as Record<RangeKey, KomariPingSample[]>,
    );
  }
  const ping = spec.ping;
  const loss = spec.loss;
  return ranges.reduce(
    (accumulator, range) => {
      const records = recent[range];
      accumulator[range] = records.map((record, index) => {
        const swing = Math.sin(index * 0.48 + spec.seed);
        const pingValue = clamp(mixToEnd(ping + swing * Math.max(1.5, ping * 0.08), ping, index, records.length), 1, 400);
        const lossValue = clamp(mixToEnd(loss + swing * (loss >= 1 ? 0.45 : 0.05), loss, index, records.length), 0, 30);
        return {
          time: record.time,
          target: "1.1.1.1",
          latest: Math.round(pingValue),
          loss: Math.round(lossValue * 10) / 10,
        };
      });
      return accumulator;
    },
    {} as Record<RangeKey, KomariPingSample[]>,
  );
}

function toBundle(spec: Spec): KomariBundle {
  const end = DEMO_NOW - spec.offlineAgo * 1000;
  const memTotal = gb(spec.memGb);
  const diskTotal = gb(spec.diskGb);
  const recent = buildRecent(spec, end);
  const client: KomariClient = {
    uuid: spec.id,
    name: spec.name,
    cpu_name: spec.cpuName,
    virtualization: spec.virt,
    arch: spec.arch,
    cpu_cores: spec.cores,
    os: spec.os,
    kernel_version: spec.kernel,
    ipv4: spec.ipv4,
    ipv6: spec.ipv6,
    region: spec.region,
    mem_total: memTotal,
    disk_total: diskTotal,
    group: spec.group,
    tags: spec.provider,
    public_remark: spec.remark,
  };
  const latest: KomariRecord = {
    client: spec.id,
    time: new Date(end).toISOString(),
    cpu: spec.cpu,
    ram: Math.round((memTotal * spec.mem) / 100),
    ram_total: memTotal,
    load: spec.load1,
    load5: spec.load5,
    load15: spec.load15,
    disk: Math.round((diskTotal * spec.disk) / 100),
    disk_total: diskTotal,
    net_in: spec.down,
    net_out: spec.up,
    net_total_up: Math.round(spec.uptimeSec * spec.up * 0.58),
    net_total_down: Math.round(spec.uptimeSec * spec.down * 0.63),
    process: spec.process,
    connections: spec.connections,
    connections_udp: spec.udp,
    temp: spec.temp,
  };
  return {
    client,
    online: spec.online,
    uptimeSec: spec.online ? spec.uptimeSec : spec.uptimeSec,
    latest,
    recent,
    ping: buildPing(spec, recent),
    observedAt: DEMO_OBSERVED_AT,
  };
}

export const DEMO_BUNDLES: KomariBundle[] = SPECS.map(toBundle);
export const BASE_NODES = adaptFleet(DEMO_BUNDLES);
